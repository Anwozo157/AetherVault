// Generates src/features/topology/landMask.ts: a 1-degree land/water bitmap of the
// world from Natural Earth 1:110m (public domain, via the world-atlas package).
// Run: node scripts/generate-land-mask.mjs   (output is committed; no runtime fetch)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoContains } from 'd3-geo';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const W = 360; // lon cells, from -180
const H = 180; // lat cells, from +90 down
const bits = new Uint8Array(Math.ceil((W * H) / 8));
let count = 0;
for (let row = 0; row < H; row++) {
  const lat = 89.5 - row;
  for (let col = 0; col < W; col++) {
    const lon = -179.5 + col;
    if (geoContains(land, [lon, lat])) {
      const i = row * W + col;
      bits[i >> 3] |= 1 << (i & 7);
      count++;
    }
  }
}

const b64 = Buffer.from(bits).toString('base64');
const out = `// GENERATED by scripts/generate-land-mask.mjs. Do not edit.
// 1° land/water bitmap (360 x 180, row 0 = 89.5°N, col 0 = 179.5°W).
// Source: Natural Earth 1:110m land (public domain) via world-atlas.
// Land cells: ${count} of ${W * H}.

const W = ${W};
const H = ${H};
const DATA = '${b64}';

let bits: Uint8Array | null = null;
function decode(): Uint8Array {
  if (!bits) {
    const bin = atob(DATA);
    bits = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) bits[i] = bin.charCodeAt(i);
  }
  return bits;
}

/** True if the 1° cell containing (lat, lon) is land. */
export function isLand(lat: number, lon: number): boolean {
  const row = Math.min(H - 1, Math.max(0, Math.floor(90 - lat)));
  const col = (((Math.floor(lon + 180) % W) + W) % W);
  const i = row * W + col;
  return (decode()[i >> 3] & (1 << (i & 7))) !== 0;
}
`;
writeFileSync(new URL('../src/features/topology/landMask.ts', import.meta.url), out);
console.log(`landMask.ts written: ${count} land cells, ${b64.length} base64 chars`);
